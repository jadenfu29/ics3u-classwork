item = input("Animal, vegetable or mineral: ")
size = input("Bigger than a breadbox: ")

if item == "animal":
    if size =="yes":
        print("squirrel")
    else:
        print("moose")
if item == "vegetable":
    if size =="yes":
        print("carrot")
    else:
        print("watermelon")
if item == "mineral":
    if size =="yes":
        print("paper clip")
    else:
        print("Camaro")